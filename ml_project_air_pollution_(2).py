import pandas as pd, zipfile, functools, numpy as np

def load_wb(path, col_name):
    with zipfile.ZipFile(path) as zf:
        names = [n for n in zf.namelist()
                 if n.lower().endswith(".csv")
                 and n.lower().startswith("api")
                 and "metadata" not in n.lower()]
        if not names:
            names = [n for n in zf.namelist() if n.lower().endswith(".csv")]
        with zf.open(names[0]) as f:
            df = pd.read_csv(f, skiprows=4, engine="python", on_bad_lines="skip", encoding="latin-1")
    df.columns = [c.strip() for c in df.columns]
    if "Country Code" not in df.columns:
        raise KeyError("No 'Country Code' column found.")
    df = df.rename(columns={"Country Code":"Country_ISO3"})
    year_cols = [c for c in df.columns if str(c).isdigit()]
    out = df.melt(id_vars=["Country_ISO3"], value_vars=year_cols,
                  var_name="Year", value_name=col_name)
    out["Year"] = pd.to_numeric(out["Year"], errors="coerce")
    out[col_name] = pd.to_numeric(out[col_name], errors="coerce")
    return out.dropna(subset=[col_name])

