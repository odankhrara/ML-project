# --- Split strategy: auto year cutoff -> per-country last year -> random ---
def build_splits(_work, _features):
    # try: 80% oldest years train, newest 20% test
    cutoff = int(_work["Year"].quantile(0.8))
    tr = _work[_work["Year"] <= cutoff].copy()
    te = _work[_work["Year"] >  cutoff].copy()
    if len(te) > 0:
        return tr, te, f"quantile_cutoff={cutoff}"

    # fallback: per-country latest year as test
    last_year = _work.groupby("Country_ISO3")["Year"].transform("max")
    te = _work[_work["Year"].eq(last_year)].copy()
    tr = _work[~_work["Year"].eq(last_year)].copy()
    if len(te) > 0:
        return tr, te, "per_country_latest_year"

    # final fallback: random split
    tr, te = train_test_split(_work, test_size=0.2, random_state=42)
    return tr.copy(), te.copy(), "random_80_20"

train, test, split_used = build_splits(work, features)
print(f"Split used: {split_used} | train={len(train)} | test={len(test)} | "
      f"years train {train['Year'].min()}–{train['Year'].max()} | years test {test['Year'].min()}–{test['Year'].max()}")

# --- Data matrices (log target) ---
Xtr, ytr = train[features], np.log1p(train[target].values)
Xte, yte = test[features],  np.log1p(test[target].values)
print("Shapes:", Xtr.shape, Xte.shape)  # make sure test > 0

